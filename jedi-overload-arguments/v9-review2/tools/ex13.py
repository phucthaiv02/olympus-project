import jedi
src = '''from typing import overload
class Foo: ...
class Bar: ...
class FooBuilder:
    def foo_m(self): ...
class BarBuilder:
    def bar_m(self): ...
@overload
def get_obj(input: type[Foo]) -> FooBuilder: ...
@overload
def get_obj(input: type[Bar]) -> BarBuilder: ...
def get_obj(input): ...
get_obj(Foo).'''
print(sorted(c.name for c in jedi.Script(src).complete() if c.name.endswith('_m')))
