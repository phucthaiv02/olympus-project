case('kw ann dict vs named', D, ['x: type[A]', 'x: type[C]'], 'f(**d)', ['RB'])
case('kw ann dict vs default', D, ['x: type[A] = A', 'x: type[C] = C'], 'f(**d)', ['RB'])
case('kw ann dict A vs named+kw', DA, ['x: type[C] = C, **kw: type[C]', 'x: type[A] = A, **kw: object'], 'f(**d)', ['RB'])
